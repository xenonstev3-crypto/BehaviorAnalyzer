args <- commandArgs(trailingOnly = TRUE)
if (length(args) < 2) stop("Usage: Rscript r_visualize_cylinder_results.R RESULT_FOLDER OUTPUT_PDF")
result_folder <- args[[1]]
output_pdf <- args[[2]]
events_path <- list.files(result_folder, pattern = "^events_.*\\.csv$", full.names = TRUE)
quality_path <- list.files(result_folder, pattern = "^frame_quality_.*\\.csv$", full.names = TRUE)
if (length(events_path) != 1 || length(quality_path) != 1) stop("Expected one events CSV and one frame_quality CSV in result folder.")
events <- read.csv(events_path[[1]], check.names = FALSE)
quality <- read.csv(quality_path[[1]], check.names = FALSE)
quality$candidate_touch <- as.integer(tolower(as.character(quality$candidate_touch)) %in% c("true", "1"))
pdf(output_pdf, width = 11, height = 8.5, onefile = TRUE)
par(mfrow = c(2, 2), mar = c(4, 4, 3, 1))
classes <- factor(events$classification, levels = c("left", "right", "bilateral"))
counts <- table(classes)
barplot(counts, col = c("#2563EB", "#DC2626", "#7C3AED"), main = "Effective touch events", ylab = "Count")
plot(NA, xlim = range(quality$time_s), ylim = c(0.5, max(1, nrow(events)) + 0.5), xlab = "Time (s)", ylab = "Event", main = "Event timeline", yaxt = "n")
cols <- c(left = "#2563EB", right = "#DC2626", bilateral = "#7C3AED")
if (nrow(events) > 0) for (i in seq_len(nrow(events))) { segments(events$start_time_s[i], i, events$end_time_s[i], i, col = cols[[events$classification[i]]], lwd = 8); text(events$start_time_s[i], i + 0.12, events$classification[i], pos = 4, cex = 0.8) }
left <- subset(quality, point == unique(quality$point)[grep("left", unique(quality$point))[1]])
right <- subset(quality, point == unique(quality$point)[grep("right", unique(quality$point))[1]])
plot(left$time_s, left$radial_distance, type = "l", col = "#2563EB", xlab = "Time (s)", ylab = "Radial distance", main = "Paw radial distance")
lines(right$time_s, right$radial_distance, col = "#DC2626"); abline(h = 100, lty = 2); legend("topright", c("Left", "Right", "Cylinder radius"), col = c("#2563EB", "#DC2626", "black"), lty = c(1,1,2), bty = "n")
quality_summary <- aggregate(candidate_touch ~ point, quality, sum)
barplot(quality_summary$candidate_touch, names.arg = quality_summary$point, las = 2, col = "#0F766E", main = "Candidate touch frames", ylab = "Frames")
dev.off()
cat(output_pdf, "\n")
